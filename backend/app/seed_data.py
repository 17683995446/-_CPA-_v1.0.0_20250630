def seed_achievements(db: Session) -> None:
    """创建成就定义。"""
    achievements = [
        ("first_study", "初次学习", "完成第一次答题", "study", 1, 50),
        ("streak_7", "坚持一周", "连续学习7天", "streak", 7, 100),
        ("streak_30", "坚持一个月", "连续学习30天", "streak", 30, 500),
        ("xp_100", "小试牛刀", "累计获得100 XP", "xp", 100, 50),
        ("xp_500", "初露锋芒", "累计获得500 XP", "xp", 500, 100),
        ("xp_1000", "学有所成", "累计获得1000 XP", "xp", 1000, 200),
        ("level_5", "稳步提升", "达到5级", "xp", 500, 100),
        ("level_10", "勤奋好学", "达到10级", "xp", 1450, 300),
    ]

    for code, name, desc, category, cond_val, xp_reward in achievements:
        existing = db.query(Achievement).filter(Achievement.code == code).first()
        if not existing:
            db.add(Achievement(
                code=code, name=name, description=desc,
                category=category, condition_type="total_xp" if category == "xp" else "streak_days",
                condition_value=cond_val, xp_reward=xp_reward,
            ))


def run_seed(db: Session) -> None:
    """执行全部种子数据初始化。"""
    code_to_id = seed_knowledge_points(db)
    seed_knowledge_edges(db, code_to_id)
    seed_questions(db, code_to_id)
    seed_achievements(db)
    db.commit()
